import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pnpmInvocation } from './lsp-runtime.mjs';

const LICENCE_FILE = /^(licen[cs]e|copying|notice|third[-_]?party[-_]?notice\w*)([-._][\w.-]*)?$/i;
const PRODUCTION_LICENCES = 'THIRD_PARTY_LICENSES.txt';
const RULE = '='.repeat(80);

const SHIPPED_TEXTS = [
  { from: 'LICENSE', to: 'LICENSE' },
  { from: 'THIRD_PARTY_NOTICES.md', to: 'THIRD_PARTY_NOTICES.md' },
  { from: path.join('website', 'src', 'fonts', 'Overpass-OFL.txt'), to: 'Overpass-OFL.txt' },
];

const SHIPPED_LICENCE_FILES = [...SHIPPED_TEXTS.map((text) => text.to), PRODUCTION_LICENCES];

const ELECTRON_TEXTS = [
  { from: 'LICENSE', to: 'ELECTRON-LICENSE' },
  { from: 'LICENSES.chromium.html', to: 'LICENSES.chromium.html' },
];

function pnpmProductionListing(root) {
  const { file, args } = pnpmInvocation(process.env.npm_execpath ?? 'pnpm', ['licenses', 'list', '--prod', '--json']);
  return execFileSync(file, args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function declaredLicence(manifest) {
  const field = manifest.license ?? manifest.licenses;
  if (typeof field === 'string') return field;
  if (Array.isArray(field)) return field.map((item) => item.type ?? item).join(' OR ');
  return field?.type ?? 'UNKNOWN';
}

function repositoryOf(manifest) {
  const url = typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url;
  return manifest.homepage ?? url ?? '';
}

function authorOf(manifest) {
  return (typeof manifest.author === 'string' ? manifest.author : manifest.author?.name) ?? '';
}

function readPackage(directory) {
  const manifest = JSON.parse(readFileSync(path.join(directory, 'package.json'), 'utf8'));
  const texts = readdirSync(directory)
    .filter((name) => LICENCE_FILE.test(name))
    .sort()
    .map((name) => readFileSync(path.join(directory, name), 'utf8').replace(/\r\n/g, '\n').trimEnd());
  return { name: manifest.name, version: manifest.version, licence: declaredLicence(manifest), author: authorOf(manifest), source: repositoryOf(manifest), texts };
}

function byNameThenVersion(a, b) {
  if (a.name !== b.name) return a.name < b.name ? -1 : 1;
  return a.version < b.version ? -1 : a.version > b.version ? 1 : 0;
}

export function productionPackages({ root = process.cwd(), listing = pnpmProductionListing } = {}) {
  const groups = JSON.parse(listing(root));
  const directories = new Set(Object.values(groups).flatMap((entries) => entries.flatMap((entry) => entry.paths)));
  const packages = new Map();
  for (const directory of directories) {
    const found = readPackage(directory);
    packages.set(`${found.name}@${found.version}`, found);
  }
  return [...packages.values()].sort(byNameThenVersion);
}

export function renderProductionLicences(packages) {
  const header = [
    'Lantern: licences of the production dependencies',
    '',
    `${packages.length} packages in the production dependency tree (pnpm licenses list --prod), each with the`,
    'licence files it ships. Generated by scripts/licenses.mjs at build time; the same list for the same lockfile.',
    '',
  ];
  const sections = packages.map((found) => {
    const lines = [RULE, `${found.name} ${found.version}`, `Licence: ${found.licence}`];
    if (found.author) lines.push(`Author: ${found.author}`);
    if (found.source) lines.push(`Source: ${found.source}`);
    lines.push('');
    lines.push(found.texts.length ? found.texts.join('\n\n') : `This package ships no licence file; its package.json declares ${found.licence}.`);
    lines.push('');
    return lines.join('\n');
  });
  return `${[...header, ...sections].join('\n')}\n`;
}

export function writeLicences({ root = process.cwd(), out = path.join(root, 'out', 'licenses'), listing } = {}) {
  for (const { from } of SHIPPED_TEXTS) {
    if (!existsSync(path.join(root, from))) throw new Error(`Cannot ship the licences: ${from} is missing`);
  }
  const packages = productionPackages({ root, listing });
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const { from, to } of SHIPPED_TEXTS) cpSync(path.join(root, from), path.join(out, to));
  writeFileSync(path.join(out, PRODUCTION_LICENCES), renderProductionLicences(packages));
  return SHIPPED_LICENCE_FILES;
}

export function packagedLayout(dist, platform, arch, productName = 'Lantern') {
  const directory = path.join(dist, `${productName}-${platform}-${arch}`);
  const resources = platform === 'darwin' ? path.join(directory, `${productName}.app`, 'Contents', 'Resources') : path.join(directory, 'resources');
  return { directory, resources };
}

export function addElectronLicences({ directory, resources }) {
  const target = path.join(resources, 'licenses');
  mkdirSync(target, { recursive: true });
  for (const { from, to } of ELECTRON_TEXTS) {
    if (!existsSync(path.join(directory, from))) throw new Error(`The packager left no ${from} in ${directory}`);
    cpSync(path.join(directory, from), path.join(target, to));
  }
  return ELECTRON_TEXTS.map((text) => text.to);
}

export { ELECTRON_TEXTS, PRODUCTION_LICENCES, SHIPPED_LICENCE_FILES };
