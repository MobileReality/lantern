import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { load, MAX_UNMAPPED_IPC } from '../src/main/lantern';
import { enumerateWithVerdicts } from '../src/main/lantern-enumerate';

const REFERENCE_SCRIPT = path.join(__dirname, '..', 'skills', 'lantern-setup', 'scripts', 'enumerate.mjs');

let project: string;

function write(rel: string, text: string | Buffer = 'export const x = 1;\n') {
  const file = path.join(project, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

async function enumerateSources(root: string) {
  return (await enumerateWithVerdicts(root)).files;
}

function paths(files: { path: string }[]) {
  return files.map((f) => f.path);
}

function writeExampleProject() {
  write('package.json', '{"name":"demo"}\n');
  write('pnpm-lock.yaml', 'lockfileVersion: 9\n');
  write('.env', 'SECRET=1\n');
  write('.env.local', 'SECRET=2\n');
  write('README.md', '# docs\n');
  write('.gitignore', 'dist/\n*.log\n/root-only.ts\n');
  write('root-only.ts');
  write('dist/out.js');
  write('debug.log', 'x\n');
  write('src/index.ts');
  write('src/app.min.js', 'x');
  write('src/logo.png', Buffer.from([0x89, 0x50, 0x00, 0x47]));
  write('src/blob.ts', Buffer.from([0x61, 0x00, 0x62]));
  write('src/gen.ts', '// @generated by tool\nexport const g = 1;\n');
  write('src/empty.ts', '');
  write('src/huge.ts', 'a'.repeat(1024 * 1024 + 1));
  write('src/util/.gitignore', 'scratch.ts\n!keep.ts\n');
  write('src/util/scratch.ts');
  write('src/util/keep.ts');
  write('src/util/helper.ts');
  write('src/service-account.json', '{}\n');
  write('vendor/lib.ts');
  write('generated/schema.ts');
  write('tools/run.sh', '#!/bin/sh\n');
  write('Dockerfile', 'FROM node\n');
  write('.lantern/ignore', 'generated/\n*.fixture.ts\n');
  write('src/case.fixture.ts');
  write('.git/info/exclude', 'private/\n');
  write('private/notes.ts');
  write('node_modules/pkg/index.js');
}

beforeEach(() => {
  project = fs.mkdtempSync(path.join(os.tmpdir(), 'ccm-enum-'));
});

afterEach(() => {
  fs.rmSync(project, { recursive: true, force: true });
});

describe('enumerateSources', () => {
  beforeEach(writeExampleProject);

  it('keeps hand-written source and drops everything skipped', async () => {
    expect(paths(await enumerateSources(project))).toEqual(['Dockerfile', 'package.json', 'src/index.ts', 'src/util/helper.ts', 'src/util/keep.ts', 'tools/run.sh']);
  });

  it('respects the root and nested .gitignore', async () => {
    const found = paths(await enumerateSources(project));
    expect(found).not.toContain('root-only.ts');
    expect(found).not.toContain('dist/out.js');
    expect(found).not.toContain('src/util/scratch.ts');
    expect(found).toContain('src/util/keep.ts');
  });

  it('respects .lantern/ignore and .git/info/exclude', async () => {
    const found = paths(await enumerateSources(project));
    expect(found).not.toContain('generated/schema.ts');
    expect(found).not.toContain('src/case.fixture.ts');
    expect(found).not.toContain('private/notes.ts');
  });

  it('skips lockfiles, .env files, binaries, generated, empty and oversized files', async () => {
    const found = paths(await enumerateSources(project));
    for (const skipped of ['pnpm-lock.yaml', '.env', '.env.local', 'src/logo.png', 'src/blob.ts', 'src/gen.ts', 'src/app.min.js', 'src/empty.ts', 'src/huge.ts', 'src/service-account.json', 'README.md']) {
      expect(found).not.toContain(skipped);
    }
  });
});

describe('lantern.load unmapped files', () => {
  it('reports a source file with no record and coverage totals', async () => {
    write('src/a.ts');
    write('src/b.ts');
    write('.lantern/map/src.lantern', ['lantern 1', '# src', 'src/a.ts . util 000000000000 | a'].join('\n'));
    const map = await load(project);
    expect(map.unmapped).toEqual(['src/b.ts']);
    expect(map.total).toBe(2);
  });

  it('reports nothing unmapped once every file has a record', async () => {
    write('src/a.ts');
    write('.lantern/map/src.lantern', ['lantern 1', '# src', 'src/a.ts . util 000000000000 | a'].join('\n'));
    expect((await load(project)).unmapped).toEqual([]);
  });

  it('does not count ignored files as unmapped', async () => {
    write('src/a.ts');
    write('src/skip.ts');
    write('.lantern/ignore', 'src/skip.ts\n');
    write('.lantern/map/src.lantern', ['lantern 1', '# src', 'src/a.ts . util 000000000000 | a'].join('\n'));
    expect((await load(project)).unmapped).toEqual([]);
  });
});

describe('lantern.load enumeration cache', () => {
  const mapA = () => write('.lantern/map/src.lantern', ['lantern 1', '# src', 'src/a.ts . util 000000000000 | a'].join('\n'));
  const sniffed = (spy: ReturnType<typeof vi.spyOn>) => spy.mock.calls.map((c) => path.relative(project, String(c[0])).split(path.sep).join('/')).sort();

  beforeEach(() => {
    write('src/a.ts');
    write('src/b.ts');
    mapA();
  });

  afterEach(() => vi.restoreAllMocks());

  it('does not re-sniff unchanged files on the second load', async () => {
    await load(project);
    const spy = vi.spyOn(fs.promises, 'open');
    const map = await load(project);
    expect(sniffed(spy)).toEqual([]);
    expect(map.unmapped).toEqual(['src/b.ts']);
    expect(map.total).toBe(2);
  });

  it('re-sniffs only the file that changed', async () => {
    await load(project);
    write('src/b.ts', 'export const changed = 12345;\n');
    const spy = vi.spyOn(fs.promises, 'open');
    await load(project);
    expect(sniffed(spy)).toEqual(['src/b.ts']);
  });

  it('drops a file whose edit made it generated', async () => {
    await load(project);
    write('src/b.ts', '// @generated by tool\nexport const g = 1;\n');
    expect((await load(project)).unmapped).toEqual([]);
  });

  it('lists a new file as unmapped and forgets a removed one', async () => {
    await load(project);
    write('src/c.ts');
    fs.rmSync(path.join(project, 'src/b.ts'));
    const map = await load(project);
    expect(map.unmapped).toEqual(['src/c.ts']);
    expect(map.total).toBe(2);
  });

  it('applies .gitignore and .lantern/ignore changes on the next load', async () => {
    await load(project);
    write('.gitignore', 'src/b.ts\n');
    expect((await load(project)).unmapped).toEqual([]);
    fs.rmSync(path.join(project, '.gitignore'));
    expect((await load(project)).unmapped).toEqual(['src/b.ts']);
    write('.lantern/ignore', 'src/b.ts\n');
    expect((await load(project)).unmapped).toEqual([]);
  });
});

describe('lantern.load unmapped cap', () => {
  it('caps the unmapped list while counts stay exact', async () => {
    const extra = 7;
    for (let i = 0; i < MAX_UNMAPPED_IPC + extra; i++) write(`src/f${String(i).padStart(4, '0')}.ts`, `export const v = ${i};\n`);
    write('.lantern/map/src.lantern', ['lantern 1', '# src'].join('\n'));
    const map = await load(project);
    expect(map.unmapped).toHaveLength(MAX_UNMAPPED_IPC);
    expect(map.unmapped[0]).toBe('src/f0000.ts');
    expect(map.unmappedCount).toBe(MAX_UNMAPPED_IPC + extra);
    expect(map.total).toBe(MAX_UNMAPPED_IPC + extra);
  });
});

describe.skipIf(!fs.existsSync(REFERENCE_SCRIPT))('parity with the reference enumerate.mjs', () => {
  it('lists the same files as the reference skill', async () => {
    writeExampleProject();
    const out = execFileSync(process.execPath, [REFERENCE_SCRIPT, project, '--json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], env: { ...process.env, ELECTRON_RUN_AS_NODE: undefined } });
    const reference = (JSON.parse(out) as { path: string; size: number }[]).map((f) => f.path);
    expect(reference.length).toBeGreaterThan(3);
    expect(paths(await enumerateSources(project))).toEqual(reference);
  });
});
