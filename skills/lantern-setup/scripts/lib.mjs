export function meetsAreasThresholds(records) {
    if (records.length <= AREAS_MIN_RECORDS_EXCLUSIVE) return false;
    return new Set(records.flatMap((record) => (record.feature ? [record.feature] : []))).size >= AREAS_MIN_FEATURES;
}

