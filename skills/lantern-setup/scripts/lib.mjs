export function dirForMapFile(file) {
    if (file === `${MAP_DIR}/${ROOT_MAP_NAME}`) return '.';
    return file.slice(MAP_DIR.length + 1, -'.lantern'.length);
}

export const DEFAULT_LANG = 'en';

export function readLang(root) {
    const valid = (v) => (/^[A-Za-z][\w-]*$/.test(v ?? '') ? v : null);
    const fromEnv = valid(process.env.LANTERN_LANG?.trim());
    if (fromEnv) return fromEnv;
    return existingMapLang(root) ?? DEFAULT_LANG;
}

function existingMapLang(root) {
    try {
        if (!fs.statSync(path.join(root, MAP_DIR)).isDirectory()) return null;
        const langs = fs.readdirSync(path.join(root, '.lantern', 'lang'), { withFileTypes: true })
            .filter((e) => e.isDirectory() && /^[A-Za-z][\w-]*$/.test(e.name)).map((e) => e.name).sort();
        return langs.includes(DEFAULT_LANG) || langs.length === 0 ? DEFAULT_LANG : langs[0];
    } catch {
        return null;
    }
}

export function loadRoles() {
    const text = fs.readFileSync(path.join(skillDir(), 'references', 'roles.md'), 'utf8');
    const roles = [...text.matchAll(/^## `([a-z-]+)`/gm)].map((m) => m[1]);
    if (roles.length === 0) throw new Error('no roles found in references/roles.md');
    return new Set(roles);
}

function splitLabel(line) {
    const bar = line.indexOf(' | ');
    if (bar === -1) return { head: line.trim(), label: '' };
    return { head: line.slice(0, bar).trim(), label: line.slice(bar + 3).trim() };
}

export function parseTarget(token) {
    if (token.startsWith(EXTERNAL_PREFIX)) return { external: token.slice(EXTERNAL_PREFIX.length), path: null, symbol: null };
    const hash = token.indexOf('#');
    const rawPath = hash === -1 ? token : token.slice(0, hash);
    const symbol = hash === -1 ? null : token.slice(hash + 1);
    return { external: null, path: decodePath(rawPath), symbol };
}

function addNote(record, kind, value, where, errors) {
    if (!record) {
        errors.push(`${where}: #${kind} before any record`);
        return;
    }
    if (!value) {
        errors.push(`${where}: #${kind} needs a value`);
        return;
    }
    const field = kind === 'feature' ? 'feature' : kind === 'gotcha' ? 'gotcha' : 'seeAlso';
    if (record[field] !== null) {
        errors.push(`${where}: second #${kind} for ${record.path}`);
        return;
    }
    if (kind === 'feature') record.feature = value;
    else if (kind === 'gotcha') record.gotcha = value;
    else {
        const { head, label } = splitLabel(value);
        record.seeAlso = head.split(/\s+/).map(decodePath);
        record.seeAlsoNote = label;
    }
    record[`${field}Where`] = where;
}

export function loadFeatures(root) {
    const file = path.join(root, FEATURES_FILE);
    if (!fs.existsSync(file)) return { features: null, lines: new Map(), errors: [] };
    const features = new Map();
    const lines = new Map();
    const errors = [];
    fs.readFileSync(file, 'utf8').split(/\r?\n/).forEach((line, index) => {
        const where = `${FEATURES_FILE}:${index + 1}`;
        if (!line.trim() || line.startsWith('#')) return;
        const { head, label } = splitLabel(line);
        if (!FEATURE_ID.test(head)) errors.push(`${where}: feature id "${head}" must be lowercase kebab-case, "<id> | <what it covers>"`);
        else if (features.has(head)) errors.push(`${where}: duplicate feature "${head}"`);
        else {
            features.set(head, label);
            lines.set(head, index + 1);
        }
    });
    return { features, lines, errors };
}

export function parseMapFile(text, file) {
    const records = [];
    const errors = [];
    const lines = text.split(/\r?\n/);
    let sawHeader = false;
    let description = null;
    let current = null;
    lines.forEach((line, index) => {
        const where = `${file}:${index + 1}`;
        if (!line.trim()) return;
        if (!sawHeader) {
            if (line.trim() !== FORMAT_HEADER) errors.push(`${where}: first line must be "${FORMAT_HEADER}"`);
            sawHeader = true;
            return;
        }
        if (line.startsWith('#')) {
            if (description === null) {
                description = line.slice(1).trim();
                return;
            }
            if (PLUMBING_NOTE.test(line)) {
                if (current && !current.plumbing) {
                    current.plumbing = true;
                    current.plumbingWhere = where;
                } else errors.push(current ? `${where}: second #${PLUMBING_NOTE_NAME} for ${current.path}` : `${where}: #${PLUMBING_NOTE_NAME} before any record`);
                return;
            }
            const note = RECORD_NOTE.exec(line);
            if (note) {
                addNote(current, note[1], note[2] ?? '', where, errors);
                return;
            }
            return;
        }
        const { head, label } = splitLabel(line);
        const tokens = head.split(/\s+/);
        if (/^\s/.test(line)) {
            if (!current) {
                errors.push(`${where}: relation before any record`);
                return;
            }
            if (tokens.length !== 2 || !ARROWS.has(tokens[0])) {
                errors.push(`${where}: relation must be "<arrow> <target> [| label]" with arrow one of > < = @`);
                return;
            }
            current.relations.push({ arrow: tokens[0], token: tokens[1], ...parseTarget(tokens[1]), label, where });
            return;
        }
        if (tokens.length !== 4) {
            errors.push(`${where}: record must be "<path> <marker> <role> <hash> | <purpose>"`);
            current = null;
            return;
        }
        const [rawPath, rawMarker, role, hash] = tokens;
        const markerMatch = /^([.~+-])(?:@([\w.-]+))?$/.exec(rawMarker);
        if (!markerMatch) {
            errors.push(`${where}: marker "${rawMarker}" must be one of . ~ + - optionally followed by @owner`);
            current = null;
            return;
        }
        current = {
            path: decodePath(rawPath),
            marker: markerMatch[1],
            owner: markerMatch[2] ?? null,
            role,
            hash,
            purpose: label,
            feature: null,
            plumbing: false,
            plumbingWhere: null,
            seeAlso: null,
            seeAlsoNote: '',
            gotcha: null,
            relations: [],
            file,
            where,
        };
        records.push(current);
    });
    if (!sawHeader) errors.push(`${file}: empty map file`);
    else if (description !== dirForMapFile(file)) errors.push(`${file}: first # line must be "# ${dirForMapFile(file)}"`);
    return { records, errors };
}

export function listMapFiles(root) {
    const base = path.join(path.resolve(root), MAP_DIR);
    const out = [];
    const walk = (dir) => {
        if (!fs.existsSync(dir)) return;
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
            const abs = path.join(dir, entry.name);
            if (entry.isDirectory()) walk(abs);
            else if (entry.name.endsWith('.lantern')) out.push(toPosix(path.relative(path.resolve(root), abs)));
        }
    };
    walk(base);
    return out.sort();
}

export function loadMap(root) {
    const records = [];
    const errors = [];
    for (const file of listMapFiles(root)) {
        const parsed = parseMapFile(fs.readFileSync(path.join(root, file), 'utf8'), file);
        records.push(...parsed.records);
        errors.push(...parsed.errors);
    }
    return { records, errors };
}
