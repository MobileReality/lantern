import fs from 'node:fs';
import path from 'node:path';
import { AGENTS_MARKER, SKILL_MARKER } from '../../scripts/lantern-bundle.mjs';
import { mapInBatches } from './lantern-batch';
import { isIgnored, isIncluded, readIgnoreFile } from './lantern-ignore';
import type { IgnoreRule } from './lantern-ignore';

const ALWAYS_SKIPPED_DIRS = new Set([
  '.git', '.hg', '.svn', '.lantern', '.claude', '.ai', '.idea', '.vscode',
  'node_modules', 'bower_components', 'vendor', '.venv', 'venv', '__pycache__',
  '.next', '.nuxt', '.svelte-kit', '.turbo', '.cache', '.parcel-cache', '.expo', '.gradle',
  'coverage', 'Pods', 'DerivedData',
]);

const SOURCE_EXTENSIONS = new Set([
  'ts', 'tsx', 'mts', 'cts', 'js', 'jsx', 'mjs', 'cjs', 'vue', 'svelte', 'astro',
  'py', 'rb', 'go', 'rs', 'java', 'kt', 'kts', 'scala', 'swift', 'm', 'mm', 'c', 'h', 'cc',
  'cpp', 'hpp', 'cs', 'fs', 'php', 'dart', 'ex', 'exs', 'erl', 'clj', 'lua', 'gd', 'r', 'jl',
  'sql', 'graphql', 'gql', 'proto', 'prisma',
  'css', 'scss', 'sass', 'less', 'styl', 'html', 'htm', 'hbs', 'ejs', 'pug', 'njk', 'liquid',
  'json', 'jsonc', 'json5', 'yaml', 'yml', 'toml', 'xml', 'gradle', 'tf', 'hcl',
  'sh', 'bash', 'zsh', 'ps1', 'psm1', 'bat', 'cmd',
]);

const MARKDOWN_EXTENSIONS = new Set(['md', 'mdx']);
const SKILL_FILE = 'SKILL.md';
const INSTRUCTION_NAMES = new Set([SKILL_FILE, 'CLAUDE.md', 'AGENTS.md', 'GEMINI.md']);
const INSTRUCTION_PATHS = new Set(['.github/copilot-instructions.md']);
const CLAUDE_DIR = '.claude';
const CLAUDE_FOLDERS = new Set(['commands', 'agents', 'rules', 'skills']);
const MAPPER_AGENT = 'lantern-mapper.md';
const CLAUDE_MARKDOWN_PREFIXES = ['commands/', 'agents/', 'rules/'].map((folder) => `${CLAUDE_DIR}/${folder}`);

const SOURCE_BASENAMES = new Set(['Dockerfile', 'Makefile', 'Rakefile', 'Gemfile', 'Procfile', 'Justfile', 'justfile', 'Taskfile']);

const LOCKFILES = new Set([
  'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lockb',
  'composer.lock', 'Gemfile.lock', 'Cargo.lock', 'poetry.lock', 'Pipfile.lock', 'go.sum',
  'Podfile.lock', 'pubspec.lock', 'mix.lock', 'uv.lock',
]);

const GENERATED_SUFFIXES = ['.min.js', '.min.css', '.map', '.bundle.js', '.chunk.js', '.pb.go', '_pb2.py', '.g.dart', '.freezed.dart'];
const GENERATED_BANNER = /@generated\b|^\/\/ Code generated .* DO NOT EDIT\.$|<auto-generated|^# This file is autogenerated/m;
const SECRET_FILE = /^\.env|\.(pem|key|p12|pfx|jks|keystore)$/i;
const SECRET_DATA_NAME = /service-?account|(^|[._-])(credentials?|secrets?)([._-]|$)/i;
const DATA_EXTENSIONS = new Set(['json', 'jsonc', 'json5', 'yaml', 'yml', 'toml', 'xml']);
const MAX_SOURCE_BYTES = 1024 * 1024;
const SNIFF_BYTES = 8000;

interface SourceFile {
  path: string;
  size: number;
}

interface SniffVerdict {
  mtimeMs: number;
  size: number;
  skip: boolean;
}

interface Candidate {
  rel: string;
  abs: string;
}

interface Enumeration {
  files: SourceFile[];
  verdicts: Map<string, SniffVerdict>;
}

function extensionOf(name: string) {
  const dot = name.lastIndexOf('.');
  return dot <= 0 ? '' : name.slice(dot + 1).toLowerCase();
}

function isSkippedByName(name: string) {
  if (SECRET_FILE.test(name)) return true;
  if (DATA_EXTENSIONS.has(extensionOf(name)) && SECRET_DATA_NAME.test(name)) return true;
  if (LOCKFILES.has(name)) return true;
  return GENERATED_SUFFIXES.some((suffix) => name.endsWith(suffix));
}

function hasSourceExtension(name: string) {
  return SOURCE_BASENAMES.has(name) || SOURCE_EXTENSIONS.has(extensionOf(name));
}

function isMarkdown(name: string) {
  return MARKDOWN_EXTENSIONS.has(extensionOf(name));
}

function isSkippedDir(rel: string, name: string) {
  if (rel === CLAUDE_DIR) return false;
  if (rel.startsWith(`${CLAUDE_DIR}/`) && rel.split('/').length === 2) return !CLAUDE_FOLDERS.has(name);
  return ALWAYS_SKIPPED_DIRS.has(name);
}

async function installedAgents(absDir: string) {
  const names = new Set([MAPPER_AGENT]);
  try {
    const [, ...owned] = (await fs.promises.readFile(path.join(absDir, AGENTS_MARKER), 'utf8')).split('\n').map((line) => line.trim()).filter(Boolean);
    for (const name of owned) names.add(name);
  } catch {}
  return names;
}

function isInstructionMarkdown(rel: string, name: string, inSkill: boolean, includeRules: IgnoreRule[]) {
  if (inSkill || INSTRUCTION_NAMES.has(name) || INSTRUCTION_PATHS.has(rel)) return true;
  if (CLAUDE_MARKDOWN_PREFIXES.some((prefix) => rel.startsWith(prefix))) return true;
  return isIncluded(includeRules, rel);
}

function isWanted(rel: string, name: string, inSkill: boolean, includeRules: IgnoreRule[]) {
  if (isMarkdown(name)) return isInstructionMarkdown(rel, name, inSkill, includeRules);
  return !rel.startsWith(`${CLAUDE_DIR}/`) && hasSourceExtension(name);
}

async function isSkippedByContent(file: string, size: number): Promise<boolean> {
  if (size === 0 || size > MAX_SOURCE_BYTES) return true;
  const handle = await fs.promises.open(file, 'r');
  try {
    const buffer = Buffer.alloc(Math.min(SNIFF_BYTES, size));
    await handle.read(buffer, 0, buffer.length, 0);
    if (buffer.includes(0)) return true;
    const head = buffer.toString('utf8').split('\n').slice(0, 5).join('\n');
    return GENERATED_BANNER.test(head);
  } finally {
    await handle.close();
  }
}

async function verdictFor(abs: string, previous: Map<string, SniffVerdict>): Promise<SniffVerdict | null> {
  try {
    const { size, mtimeMs } = await fs.promises.stat(abs);
    const cached = previous.get(abs);
    if (cached && cached.mtimeMs === mtimeMs && cached.size === size) return cached;
    return { mtimeMs, size, skip: await isSkippedByContent(abs, size) };
  } catch {
    return null;
  }
}

async function collectCandidates(absRoot: string): Promise<Candidate[]> {
  const candidates: Candidate[] = [];
  const lanternRules = await readIgnoreFile(path.join(absRoot, '.lantern', 'ignore'), '');
  const includeRules = await readIgnoreFile(path.join(absRoot, '.lantern', 'include'), '');
  const isExcluded = (rules: IgnoreRule[], rel: string, isDir: boolean) => isIgnored(rules, rel, isDir) || isIgnored(lanternRules, rel, isDir);

  const walk = async (relDir: string, inherited: IgnoreRule[], inSkill: boolean) => {
    const absDir = path.join(absRoot, relDir);
    const rules = [...inherited, ...(await readIgnoreFile(path.join(absDir, '.gitignore'), relDir))];
    let entries: fs.Dirent[];
    try {
      entries = await fs.promises.readdir(absDir, { withFileTypes: true });
    } catch {
      return;
    }
    entries.sort((a, b) => (a.name < b.name ? -1 : 1));
    if (entries.some((entry) => entry.name === SKILL_MARKER && entry.isFile())) return;
    const skill = inSkill || entries.some((entry) => entry.name === SKILL_FILE && entry.isFile());
    const installed = relDir === `${CLAUDE_DIR}/agents` ? await installedAgents(absDir) : null;
    for (const entry of entries) {
      const rel = relDir ? `${relDir}/${entry.name}` : entry.name;
      if (entry.isSymbolicLink()) continue;
      if (entry.isDirectory()) {
        if (isSkippedDir(rel, entry.name) || isExcluded(rules, rel, true)) continue;
        await walk(rel, rules, skill);
        continue;
      }
      if (!entry.isFile() || isExcluded(rules, rel, false) || installed?.has(entry.name)) continue;
      if (isSkippedByName(entry.name) || !isWanted(rel, entry.name, skill, includeRules)) continue;
      candidates.push({ rel, abs: path.join(absRoot, rel) });
    }
  };

  await walk('', await readIgnoreFile(path.join(absRoot, '.git', 'info', 'exclude'), ''), false);
  return candidates;
}

async function enumerateWithVerdicts(root: string, previous: Map<string, SniffVerdict> = new Map()): Promise<Enumeration> {
  const candidates = await collectCandidates(path.resolve(root));
  const results = await mapInBatches(candidates, (c) => verdictFor(c.abs, previous));
  const files: SourceFile[] = [];
  const verdicts = new Map<string, SniffVerdict>();
  candidates.forEach((c, i) => {
    const verdict = results[i];
    if (!verdict) return;
    verdicts.set(c.abs, verdict);
    if (!verdict.skip) files.push({ path: c.rel, size: verdict.size });
  });
  return { files, verdicts };
}

export { enumerateWithVerdicts };
export type { SourceFile, SniffVerdict };
